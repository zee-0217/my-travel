import assert from 'node:assert/strict';
import { createBrowserClient } from './browser-client.mjs';
import { createSampleTrip } from '../public/js/sample-data.js';

const trip = { ...createSampleTrip({ region: '부산', startDate: '2026-12-01', duration: 2, travelers: 2, budget: 500000, preferences: ['자연'], transport: 'car', requests: '' }), isSample: false, title: '저장 기능 검사 여행', planId: '11111111-1111-4111-8111-111111111111', sources: [], trace: [], apiKey: 'must-never-be-persisted' };
const browser = await createBrowserClient();
const key = 'travel-piece.saved-trips.v1';
try {
  await browser.command('Page.addScriptToEvaluateOnNewDocument', { source: `const originalFetch=window.fetch.bind(window);window.fetch=(url,options)=>url==='/api/plan'?Promise.resolve(new Response(JSON.stringify({plan:${JSON.stringify(trip)}}),{headers:{'Content-Type':'application/json'}})):originalFetch(url,options);` });
  await browser.command('Page.navigate', { url: 'http://localhost:3000' });
  await browser.until("document.documentElement.dataset.appReady === 'true'");
  assert.equal(await browser.evaluate("document.querySelector('#save-trip-button').disabled"), true);
  await browser.click('#generate-button');
  await browser.until("document.querySelector('#results-title').textContent === '저장 기능 검사 여행'");
  await browser.click('#save-trip-button');
  assert.equal(await browser.evaluate("document.querySelectorAll('.saved-trip-card').length"), 1);
  const stored = await browser.evaluate(`localStorage.getItem('${key}')`);
  assert.ok(!stored.includes('must-never-be-persisted')); assert.ok(!stored.includes('11111111-1111'));
  await browser.click('.saved-trip-edit');
  await browser.evaluate(`document.querySelector('#saved-edit-title').value='수정한 부산 여행';document.querySelector('#saved-edit-note').value='우산과 편한 신발';document.querySelector('[data-edit-field="time"]').value='11:00';document.querySelector('[data-edit-field="endTime"]').value='11:30';document.querySelector('[data-edit-field="personalNote"]').value='<img src=x onerror=alert(1)>';`);
  await browser.click('#saved-edit-submit');
  assert.equal(await browser.evaluate("document.querySelector('#results-title').textContent"), '수정한 부산 여행');
  assert.match(await browser.evaluate("document.querySelector('#timeline').textContent"), /11:00~11:30/);
  assert.match(await browser.evaluate("document.querySelector('#personal-trip-note').textContent"), /우산과 편한 신발/);
  assert.equal(await browser.evaluate("document.querySelectorAll('#timeline img').length"), 0);
  await browser.command('Page.reload', { ignoreCache: true });
  await browser.until("document.documentElement.dataset.appReady === 'true'");
  assert.equal(await browser.evaluate("document.querySelectorAll('.saved-trip-card').length"), 1);
  await browser.click('.saved-trip-open');
  assert.equal(await browser.evaluate("document.querySelector('#results-title').textContent"), '수정한 부산 여행');
  assert.equal(await browser.evaluate("document.querySelector('#region-select').value"), '부산');
  assert.equal(await browser.evaluate("document.querySelector('#chat-submit').disabled"), true);
  assert.match(await browser.evaluate("document.querySelector('#chat-status').textContent"), /직접 수정/);
  await browser.evaluate("const originalCreateURL=URL.createObjectURL;URL.createObjectURL=(blob)=>{blob.text().then(text=>window.exportedPlan=text);return originalCreateURL(blob)}");
  await browser.click('.saved-trip-export');
  await browser.until('Boolean(window.exportedPlan)');
  const exported = JSON.parse(await browser.evaluate('window.exportedPlan'));
  assert.equal(exported.title, '수정한 부산 여행'); assert.equal(exported.days[0].stops[0].time, '11:00');
  assert.ok(!JSON.stringify(exported).includes('must-never-be-persisted'));
  await browser.click('#save-trip-copy'); assert.equal(await browser.evaluate("document.querySelectorAll('.saved-trip-card').length"), 2);
  await browser.click('.saved-trip-delete'); await browser.click('.saved-trip-delete');
  assert.equal(await browser.evaluate("document.querySelector('#saved-trips-empty').hidden"), false);
  await browser.evaluate("Storage.prototype.setItem=function(){throw new DOMException('full','QuotaExceededError')}");
  await browser.click('#save-trip-button');
  assert.equal(await browser.evaluate("document.querySelector('#saved-trips-error').hidden"), false);
  assert.equal(await browser.evaluate(`JSON.parse(localStorage.getItem('${key}')).trips.length`), 0);
  assert.deepEqual(browser.errors, []);
  console.log(JSON.stringify({ status: 'passed', fixtureOnly: true, checks: ['save and list', 'sensitive field exclusion', 'manual schedule edit and notes', 'safe text rendering', 'reload and open in existing screen', 'restored travel conditions', 'JSON export contents', 'copy and deletion', 'quota error preserves data'] }));
} finally { await browser.close(); }
